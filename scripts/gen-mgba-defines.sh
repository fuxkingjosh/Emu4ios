#!/bin/bash
# Turns the compile definitions mGBA was built with into a header,
# so our bridge sees the exact same struct layouts as the library.
# usage: gen-mgba-defines.sh <mgba-build-dir> <output-header>
set -euo pipefail
FLAGS_FILE="$1/CMakeFiles/mgba.dir/flags.make"
OUT="$2"
{
  echo "// Generated by scripts/gen-mgba-defines.sh — do not edit."
  echo "#pragma once"
  grep -h "^C_DEFINES" "$FLAGS_FILE" | sed 's/^C_DEFINES = //' | tr ' ' '\n' | grep '^-D' | sed 's/^-D//' | while read -r def; do
    name="${def%%=*}"
    case "$name" in _GNU_SOURCE|BUILD_STATIC) continue;; esac
    if [[ "$def" == *=* ]]; then value="${def#*=}"; else value=""; fi
    echo "#ifndef $name"
    echo "#define $name $value"
    echo "#endif"
  done
} > "$OUT"
